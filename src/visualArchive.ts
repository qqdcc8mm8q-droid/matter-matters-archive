function sel(id: string, label: string, options: { value: string; label: string }[]): ToolDef['params'][number] {
  return { id, label, kind: 'select', options }
}

function num(id: string, label: string, min: number, max: number, step: number): ToolDef['params'][number] {
  return { id, label, kind: 'number', min, max, step }
}

function fx(id: string, name: string, summary: string, params: ToolDef['params'], defaults: Record<string, string>): ToolDef {
  return { id, name, category: 'Image', summary, inputs: layerIn, outputs: layerOut, params, defaults }
}

function typeTool(
  id: string,
  name: string,
  summary: string,
  params: ToolDef['params'],
  defaults: Record<string, string>,
  inputs: ToolDef['inputs'] = colorIn,
): ToolDef {
  return { id, name, category: 'Type', summary, inputs, outputs: layerOut, params, defaults }
}

function pattern(id: string, name: string, summary: string, params: ToolDef['params'], defaults: Record<string, string>): ToolDef {
  return { id, name, category: 'Pattern', summary, inputs: colorIn, outputs: layerOut, params, defaults }
}

